package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"slices"
	"strings"
)

// The scenario registration: the feature files whose scenarios have steps,
// each declared beside its steps' initializer in a file of package
// features, listed in features/steps_gen.go.

// featureRoot is the folder of the feature files and their steps, from the
// repository's root.
const featureRoot = "features"

// steppedOutput is the file the scenario registration is written to.
const steppedOutput = featureRoot + "/steps_gen.go"

// stepped is one declaration of a feature file's steps: the Go file that
// holds it, the variable it is and the feature file its Name names.
type stepped struct {
	file, variable, name string
}

// registration is the source of features/steps_gen.go over the
// declarations in tree's features/*.go, or why one of them is refused.
func registration(tree fs.FS) ([]byte, error) {
	found, err := declarations(tree)
	if err != nil {
		return nil, err
	}
	return renderStepped(found)
}

// declarations are the featureFile declarations of the Go files right in
// tree's features/, its tests, subfolders and steps_gen.go left out, in
// their Names' order, or why one is refused.
func declarations(tree fs.FS) ([]stepped, error) {
	entries, err := fs.ReadDir(tree, featureRoot)
	if err != nil {
		return nil, err
	}
	var found []stepped
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		file := featureRoot + "/" + name
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || file == steppedOutput {
			continue
		}
		src, err := fs.ReadFile(tree, file)
		if err != nil {
			return nil, err
		}
		f, err := parser.ParseFile(fset, file, src, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		each, err := featureFiles(f, file)
		if err != nil {
			return nil, err
		}
		for _, s := range each {
			if i := slices.IndexFunc(found, func(o stepped) bool { return o.name == s.name }); i >= 0 {
				return nil, refused{fmt.Sprintf("%s and %s both declare the steps of %q: a feature file has one declaration", found[i].file, s.file, s.name)}
			}
			if _, err := fs.Stat(tree, featureRoot+"/"+s.name); err != nil || strings.Contains(s.name, "/") {
				return nil, refused{fmt.Sprintf("%s: %s declares the steps of %q, and %s holds no such file", s.file, s.variable, s.name, featureRoot)}
			}
			found = append(found, s)
		}
	}
	slices.SortFunc(found, func(x, y stepped) int { return strings.Compare(x.name, y.name) })
	return found, nil
}

// featureFiles are the package-level var <name> = featureFile{…}
// declarations of f, the file at path, or why one is refused: a Name that
// is no non-empty string literal, or no Steps.
func featureFiles(f *ast.File, path string) ([]stepped, error) {
	var found []stepped
	for _, d := range f.Decls {
		g, isGen := d.(*ast.GenDecl)
		if !isGen || g.Tok != token.VAR {
			continue
		}
		for _, spec := range g.Specs {
			v := spec.(*ast.ValueSpec)
			if len(v.Names) != len(v.Values) {
				continue
			}
			for i, value := range v.Values {
				lit, isLit := value.(*ast.CompositeLit)
				if !isLit {
					continue
				}
				if t, isIdent := lit.Type.(*ast.Ident); !isIdent || t.Name != "featureFile" {
					continue
				}
				s, err := featureFileOf(lit, path, v.Names[i].Name)
				if err != nil {
					return nil, err
				}
				found = append(found, s)
			}
		}
	}
	return found, nil
}

// featureFileOf is the declaration lit, of the variable variable in the file
// at path, or why it is refused.
func featureFileOf(lit *ast.CompositeLit, path, variable string) (stepped, error) {
	s := stepped{file: path, variable: variable}
	var named, steps bool
	for _, el := range lit.Elts {
		kv, isKV := el.(*ast.KeyValueExpr)
		if !isKV {
			continue
		}
		key, isIdent := kv.Key.(*ast.Ident)
		if !isIdent {
			continue
		}
		switch key.Name {
		case "Name":
			s.name, named = stringOf(kv.Value)
			named = named && s.name != ""
		case "Steps":
			steps = true
		}
	}
	switch {
	case !named:
		return stepped{}, refused{fmt.Sprintf("%s: %s names its feature file by no non-empty string literal: give featureFile a Name such as Name: \"units.feature\"", path, variable)}
	case !steps:
		return stepped{}, refused{fmt.Sprintf("%s: %s declares %q with no Steps: give featureFile the initializer of its steps, such as Steps: unitSteps", path, variable, s.name)}
	}
	return s, nil
}

// steppedHeader is the registration's first lines, the standard line go
// tooling and golangci-lint read a generated file by among them.
const steppedHeader = `// Code generated by tools/bin/assemble from features; DO NOT EDIT.
// Run go run ./tools/bin/assemble after giving a feature file's steps a
// declaration, or removing or renaming one.

package features

// stepped are the feature files whose scenarios have steps, each declared
// beside its steps' initializer (featureFile), in their names' order:
// Converted names them, and initialize gives a scenario each one's steps in
// this order.
var stepped = []featureFile{
`

// renderStepped is the registration's source over found, in their names'
// order, formatted by go/format.
func renderStepped(found []stepped) ([]byte, error) {
	var b strings.Builder
	b.WriteString(steppedHeader)
	for _, s := range found {
		fmt.Fprintf(&b, "\t%s,\n", s.variable)
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}
