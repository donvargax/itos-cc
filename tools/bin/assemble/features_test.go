// stepsSource is a file of package features declaring, as variable, the
// steps of the feature file name, given by initializer.
func stepsSource(variable, name, initializer string) string {
	return `package features

import "github.com/cucumber/godog"

var ` + variable + ` = featureFile{Name: "` + name + `", Steps: ` + initializer + `}

func ` + initializer + `(sc *godog.ScenarioContext, w *world) {}
`
}

// Every declaration is in the registration, in its Name's order, whatever
// file holds it, the file formatted and marked generated. A test's
// declaration, a subfolder's and a feature file with none are not.
func TestTheRegistrationListsEveryDeclarationInItsNamesOrder(t *testing.T) {
	root := treeOf(t, map[string]string{
		"features/alpha.go":              stepsSource("zuluFeature", "zulu.feature", "zuluSteps"),
		"features/beta.go":               stepsSource("alphaFeature", "alpha.feature", "alphaSteps") + "\nvar mikeFeature = featureFile{Name: \"mike.feature\", Steps: alphaSteps}\n",
		"features/alpha.feature":         "Feature: alpha\n",
		"features/mike.feature":          "Feature: mike\n",
		"features/zulu.feature":          "Feature: zulu\n",
		"features/serve.feature":         "Feature: no steps yet\n",
		"features/tested_test.go":        stepsSource("testedFeature", "serve.feature", "testedSteps"),
		"features/testdata/nested.go":    stepsSource("nestedFeature", "serve.feature", "nestedSteps"),
		"features/README.md":             "not Go\n",
		"internal/slices/units/units.go": sliceSource("units", "units"),
	})
	code, stderr, _ := generate(t, root, false)
	if code != 0 {
		t.Fatalf("exit %d: %s", code, stderr)
	}
	file := writtenAt(root, steppedOutput)
	if !strings.HasPrefix(file, "// Code generated by tools/bin/assemble from features; DO NOT EDIT.\n") {
		t.Errorf("the file does not start with the generated line:\n%s", file)
	}
	at := 0
	for _, part := range []string{"var stepped = []featureFile{\n", "\talphaFeature,\n", "\tmikeFeature,\n", "\tzuluFeature,\n", "}\n"} {
		i := strings.Index(file[at:], part)
		if i < 0 {
			t.Fatalf("%q missing or out of order in\n%s", part, file)
		}
		at += i + len(part)
	}
	for _, absent := range []string{"tested", "nested", "serve"} {
		if strings.Contains(file, absent) {
			t.Errorf("the file holds %q, from no declaration it reads:\n%s", absent, file)
		}
	}
	if _, err := parser.ParseFile(token.NewFileSet(), steppedOutput, file, 0); err != nil {
		t.Errorf("the file does not parse: %v", err)
	}
	if code, stderr, _ := generate(t, root, true); code != 0 {
		t.Errorf("-check over the files it wrote: exit %d, %s", code, stderr)
	}
	if code, stderr, _ := generate(t, root, false); code != 0 || writtenAt(root, steppedOutput) != file {
		t.Errorf("a second run, its own output in features/: exit %d, %s, the file changed", code, stderr)
	}
}

// -check writes nothing, and fails naming the registration when it is not
// what assemble writes, or missing, and not the assembly when that is
// current.
func TestCheckNamesTheRegistrationWhenNotCurrent(t *testing.T) {
	root := treeOf(t, map[string]string{"internal/slices/units/units.go": sliceSource("units", "units")})
	code, stderr, _ := generate(t, root, true)
	if code != 1 || !strings.Contains(stderr, steppedOutput+" is not what the declarations in features/*.go list") || writtenAt(root, steppedOutput) != "" {
		t.Errorf("a missing registration: exit %d, %q; want 1 naming %s and nothing written", code, stderr, steppedOutput)
	}
	if code, _, _ := generate(t, root, false); code != 0 {
		t.Fatal("cannot write the files")
	}
	stale := filepath.Join(root, filepath.FromSlash(steppedOutput))
	if err := os.WriteFile(stale, []byte("package features\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	code, stderr, _ = generate(t, root, true)
	if code != 1 || !strings.Contains(stderr, steppedOutput) || strings.Contains(stderr, output) || writtenAt(root, steppedOutput) != "package features\n" {
		t.Errorf("a stale registration: exit %d, %q; want 1 naming %s alone and the file untouched", code, stderr, steppedOutput)
	}
}

// A declaration assemble cannot register is refused, naming its Go file or
// files, and nothing is written.
func TestADeclarationItCannotRegisterIsRefusedByName(t *testing.T) {
	units := stepsSource("unitsFeature", "units.feature", "unitSteps")
	for _, c := range []struct {
		name  string
		files map[string]string
		want  string
	}{
		{"a name that is no literal", map[string]string{
			"features/units.go":      strings.Replace(units, `Name: "units.feature"`, "Name: name", 1),
			"features/units.feature": "Feature: units\n",
		}, "features/units.go: unitsFeature names its feature file by no non-empty string literal"},
		{"an empty name", map[string]string{
			"features/units.go":      strings.Replace(units, `Name: "units.feature"`, `Name: ""`, 1),
			"features/units.feature": "Feature: units\n",
		}, "features/units.go: unitsFeature names its feature file by no non-empty string literal"},
		{"no Steps", map[string]string{
			"features/units.go":      strings.Replace(units, ", Steps: unitSteps", "", 1),
			"features/units.feature": "Feature: units\n",
		}, `features/units.go: unitsFeature declares "units.feature" with no Steps`},
		{"two of one name", map[string]string{
			"features/units.go":      units,
			"features/more.go":       stepsSource("moreFeature", "units.feature", "moreSteps"),
			"features/units.feature": "Feature: units\n",
		}, `features/more.go and features/units.go both declare the steps of "units.feature"`},
		{"a name with no such file", map[string]string{
			"features/units.go": units,
		}, `features/units.go: unitsFeature declares the steps of "units.feature", and features holds no such file`},
	} {
		c.files["internal/slices/units/units.go"] = sliceSource("units", "units")
		root := treeOf(t, c.files)
		code, stderr, file := generate(t, root, false)
		if code != 1 || file != "" || writtenAt(root, steppedOutput) != "" {
			t.Errorf("%s: exit %d, %q, wrote %q; want 1 and nothing written", c.name, code, stderr, file)
		}
		if !strings.Contains(stderr, c.want) {
			t.Errorf("%s: %q, want %q", c.name, stderr, c.want)
		}
	}
}

// A features/ folder that cannot be read is exit 2, nothing written.
func TestAnUnreadableFeaturesFolderIsExitTwo(t *testing.T) {
	root := treeOf(t, map[string]string{"internal/slices/units/units.go": sliceSource("units", "units")})
	folder := filepath.Join(root, featureRoot)
	if err := os.RemoveAll(folder); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(folder, []byte("not a folder\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	code, stderr, file := generate(t, root, false)
	if code != 2 || file != "" || !strings.Contains(stderr, "features") {
		t.Errorf("exit %d, %q, wrote %q; want 2 naming features and nothing written", code, stderr, file)
	}
}
