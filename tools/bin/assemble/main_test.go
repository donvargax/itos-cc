// sliceSource is the source of a slice of package pkg declaring the command name,
// with its Ports.
func sliceSource(pkg, name string) string {
	return "package " + pkg + `

import (
	"context"

	"example.com/shop/internal/cli"
)

var Command = cli.Declaration{Name: "` + name + `", Help: "a command", New: func() any { return &CLI{} }}

type CLI struct{}

type Handler struct{}

type Ports interface{ SelectionTree() any }

func NewHandler(ctx context.Context, p Ports) (Handler, error) { return Handler{}, nil }
`
}

// treeOf is a repository of module example.com/shop holding files, by their
// paths from its root, and cmd/itos-cc's main, and its root.
func treeOf(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	files["go.mod"] = "module example.com/shop\n\ngo 1.27\n"
	files["cmd/itos-cc/main.go"] = "package main\n"
	for name, text := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// generate runs assemble over root and returns its exit status, what it
// said and the file it wrote.
func generate(t *testing.T, root string, check bool) (int, string, string) {
	t.Helper()
	var stderr strings.Builder
	code := run(root, check, nil, &stderr)
	written, _ := os.ReadFile(filepath.Join(root, filepath.FromSlash(output)))
	return code, stderr.String(), string(written)
}

// Every slice is in the file: imported in its path's order, its command
// registered and its handler provided in its name's order, the file
// formatted and marked generated. A slice's tests and subfolders are not
// read, so a declaration there is no slice.
func TestTheFileAssemblesEverySliceInItsNamesOrder(t *testing.T) {
	root := treeOf(t, map[string]string{
		"internal/slices/beta/beta.go":           sliceSource("beta", "omega"),
		"internal/slices/zeta/zeta.go":           sliceSource("zeta", "alpha"),
		"internal/slices/zeta/zeta_test.go":      sliceSource("zeta", "tested"),
		"internal/slices/zeta/port/port.go":      sliceSource("port", "nested"),
		"internal/slices/kong/kong.go":           sliceSource("kong", "middle"),
		"internal/slices/README.md":              "not a slice\n",
		"internal/slices/beta/porttest/fakes.go": "package porttest\n",
	})
	code, stderr, file := generate(t, root, false)
	if code != 0 {
		t.Fatalf("exit %d: %s", code, stderr)
	}
	if !strings.HasPrefix(file, "// Code generated by tools/bin/assemble from internal/slices; DO NOT EDIT.\n") {
		t.Errorf("the file does not start with the generated line:\n%s", file)
	}
	inOrder := func(what string, parts ...string) {
		t.Helper()
		at := 0
		for _, part := range parts {
			i := strings.Index(file[at:], part)
			if i < 0 {
				t.Errorf("%s: %q missing or out of order in\n%s", what, part, file)
				return
			}
			at += i + len(part)
		}
	}
	inOrder("imports", `"example.com/shop/internal/slices/beta"`, `kongslice "example.com/shop/internal/slices/kong"`, `"example.com/shop/internal/slices/zeta"`)
	inOrder("registrations", "zeta.Command.New()", "kongslice.Command.New()", "beta.Command.New()", "kong.PostBuild(byName)")
	inOrder("providers", "kong.PostBuild(byName)", "(zeta.Handler, error) { return zeta.NewHandler(ctx, a) }", "kongslice.NewHandler(ctx, a)", "beta.NewHandler(ctx, a)")
	for _, absent := range []string{"tested", "nested", "port.", "porttest"} {
		if strings.Contains(file, absent) {
			t.Errorf("the file holds %q, from no slice:\n%s", absent, file)
		}
	}
	if _, err := parser.ParseFile(token.NewFileSet(), output, file, 0); err != nil {
		t.Errorf("the file does not parse: %v", err)
	}
	if code, stderr, _ := generate(t, root, true); code != 0 {
		t.Errorf("-check over the file it wrote: exit %d, %s", code, stderr)
	}
}

// -check writes nothing, and fails naming the file when it is not what
// assemble writes, or missing.
func TestCheckRefusesAFileThatIsNotCurrent(t *testing.T) {
	root := treeOf(t, map[string]string{"internal/slices/units/units.go": sliceSource("units", "units")})
	if code, stderr, file := generate(t, root, true); code != 1 || !strings.Contains(stderr, output+" is not what the slices") || file != "" {
		t.Errorf("a missing file: exit %d, %q, wrote %q; want 1 naming %s and nothing written", code, stderr, file, output)
	}
	if code, _, _ := generate(t, root, false); code != 0 {
		t.Fatal("cannot write the file")
	}
	stale := filepath.Join(root, filepath.FromSlash(output))
	if err := os.WriteFile(stale, []byte("package main\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if code, stderr, file := generate(t, root, true); code != 1 || !strings.Contains(stderr, output) || file != "package main\n" {
		t.Errorf("a stale file: exit %d, %q, file %q; want 1 naming %s and the file untouched", code, stderr, file, output)
	}
}

// A slice cmd could not assemble is refused, naming it, and nothing is
// written.
func TestASliceItCannotAssembleIsRefusedByName(t *testing.T) {
	noPorts := strings.Replace(sliceSource("dry", "dry"), "type Ports interface{ SelectionTree() any }", "", 1)
	for _, c := range []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{"no declaration", map[string]string{
			"internal/slices/units/units.go": sliceSource("units", "units"),
			"internal/slices/scrap/scrap.go": "package scrap\n\ntype Ports interface{}\n",
		}, []string{"internal/slices/scrap declares no command"}},
		{"a declaration only a test holds", map[string]string{
			"internal/slices/scrap/scrap.go":      "package scrap\n",
			"internal/slices/scrap/scrap_test.go": sliceSource("scrap", "scrap"),
		}, []string{"internal/slices/scrap declares no command"}},
		{"no Ports", map[string]string{"internal/slices/dry/dry.go": noPorts}, []string{"internal/slices/dry declares its command but no Ports"}},
		{"two with one name", map[string]string{
			"internal/slices/crap/crap.go":   sliceSource("crap", "units"),
			"internal/slices/units/units.go": sliceSource("units", "units"),
		}, []string{"internal/slices/crap and internal/slices/units both declare the command \"units\""}},
		{"a name that is no literal", map[string]string{
			"internal/slices/units/units.go": strings.Replace(sliceSource("units", "units"), `Name: "units"`, "Name: name", 1),
		}, []string{"internal/slices/units: its Command names its command by no string literal"}},
	} {
		code, stderr, file := generate(t, treeOf(t, c.files), false)
		if code != 1 || file != "" {
			t.Errorf("%s: exit %d, wrote %q; want 1 and nothing written", c.name, code, file)
		}
		for _, want := range c.want {
			if !strings.Contains(stderr, want) {
				t.Errorf("%s: %q, want %q", c.name, stderr, want)
			}
		}
	}
}
